import assert from 'node:assert/strict';
import {planCrossFileMasks,migrateNotePadding} from '../dist/independent-editor-operations.js';
const makePage=(width,height,rotation=0)=>({origW:900,origH:Math.round(900*height/width),pdfW:width,pdfH:height,rotation,bakedRects:[],pendingRects:[],stickyNotes:[]});
const source=makePage(200,100);
source.pendingRects=[{x:90,y:60,w:180,h:120}];
const identical=makePage(200,100);
identical.bakedRects=[{x:20,y:20,w:10,h:10}];
const different=makePage(100,100);
const extra=makePage(100,100);
const files=[{pages:[source]},{pages:[identical,extra]},{pages:[different]}];
const plan=planCrossFileMasks(files,0,0);
assert.equal(plan.length,3);
assert.deepEqual(plan[0],{fileIndex:0,pageIndex:0,kind:'bakedRects',rects:[{x:90,y:60,w:180,h:120}]});
assert.deepEqual(plan[1],{fileIndex:1,pageIndex:0,kind:'bakedRects',rects:[{x:90,y:60,w:180,h:120}]});
assert.deepEqual(plan[2],{fileIndex:2,pageIndex:0,kind:'pendingRects',rects:[{x:90,y:120,w:180,h:240}]});
assert.deepEqual(extra.pendingRects,[],'later pages remain untouched');
assert.deepEqual(identical.bakedRects,[{x:20,y:20,w:10,h:10}],'planning leaves prior edits untouched');
assert.deepEqual(planCrossFileMasks(files,0,0).length,3,'planning does not mutate source');
source.pendingRects=[];
assert.deepEqual(planCrossFileMasks(files,0,0),[],'no selected red frames means no batch');
const rotated=makePage(200,100,90);
rotated.pendingRects=[{x:45,y:90,w:90,h:180}];
const portrait=makePage(100,200);
const portraitPlan=planCrossFileMasks([{pages:[rotated]},{pages:[portrait]}],0,0);
assert.equal(portraitPlan[1].kind,'bakedRects','matching displayed physical dimensions mask immediately');
assert.deepEqual(portraitPlan[1].rects,[{x:90,y:180,w:180,h:360}]);
const sourceSecond=makePage(200,100);sourceSecond.pendingRects=[{x:90,y:60,w:180,h:120}];
const firstOfSource=makePage(200,100);
const secondPlan=planCrossFileMasks([{pages:[firstOfSource,sourceSecond]},{pages:[makePage(200,100)]}],0,1);
assert.deepEqual(secondPlan.map(item=>item.pageIndex),[1,0],'source current page and only other files first page change');
assert.deepEqual(firstOfSource.bakedRects,[]);
const duplicateSource=makePage(200,100);duplicateSource.pendingRects=[{x:90,y:60,w:180,h:120}];duplicateSource.bakedRects=[{x:90,y:60,w:180,h:120}];
const duplicateTarget=makePage(200,100);duplicateTarget.bakedRects=[{x:90,y:60,w:180,h:120}];duplicateTarget.pendingRects=[{x:90,y:60,w:180,h:120}];
const duplicatePlan=planCrossFileMasks([{pages:[duplicateSource]},{pages:[duplicateTarget]}],0,0);
assert.deepEqual(duplicatePlan[0].rects,[],'source still consumes a duplicate pending red frame');
assert.deepEqual(duplicatePlan[1].pendingToRemove,[{x:90,y:60,w:180,h:120}],'same-size target removes existing red duplicate over a white mask');
const stored={version:11,files:[{pages:[{stickyNotes:[{padding:6,h:80,manualH:30}]}],history:[{pages:[{stickyNotes:[{padding:8,h:40,manualH:20}]}]}],future:[{pages:[{stickyNotes:[{padding:10,h:60,manualH:25}]}]}]}]};
migrateNotePadding(stored);
assert.equal(stored.notePaddingVersion,2);
assert.deepEqual(stored.files[0].pages[0].stickyNotes[0],{padding:3,h:80,manualH:80});
assert.deepEqual(stored.files[0].history[0].pages[0].stickyNotes[0],{padding:4,h:40,manualH:40});
assert.deepEqual(stored.files[0].future[0].pages[0].stickyNotes[0],{padding:5,h:60,manualH:60});
migrateNotePadding(stored);
assert.equal(stored.files[0].pages[0].stickyNotes[0].padding,3,'padding migration is idempotent');
console.log('PASS: cross-file planning and one-time existing-note padding migration');
